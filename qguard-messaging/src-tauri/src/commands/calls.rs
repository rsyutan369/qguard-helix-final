    // ---- version 2: per-call key + caller signature -------------------------

    fn registered(identity: &LocalIdentity) -> CallPeerIdentity {
        let bundle = identity.public_bundle().unwrap();
        CallPeerIdentity {
            user_id: bundle.user_id,
            device_id: bundle.device_id,
            x25519_identity_public: bundle.x25519_identity_public,
            mlkem_identity_public: bundle.mlkem_identity_public,
            ed25519_identity_public: bundle.ed25519_identity_public,
            mldsa_identity_public: bundle.mldsa_identity_public,
            identity_signature: bundle.signature,
        }
    }

    /// A callee that has just accepted `call_id` from `caller`.
    fn accepted(
        callee: &LocalIdentity,
        caller: &LocalIdentity,
        call_id: &str,
    ) -> (PendingCallKey, CallEphemeralKey) {
        let keypair = LocalKemKeypair::generate();
        let public =
            sign_ephemeral_key(callee, call_id, &caller.user_id, &caller.device_id, &keypair).unwrap();
        let pending = PendingCallKey {
            keypair,
            caller_user_id: caller.user_id.clone(),
            caller_device_id: caller.device_id.clone(),
            created_at: 0,
        };
        (pending, public)
    }

    fn two_devices() -> (LocalIdentity, LocalIdentity) {
        (
            LocalIdentity::generate("user-caller", "Desktop").unwrap(),
            LocalIdentity::generate("user-callee", "Phone").unwrap(),
        )
    }

    #[test]
    fn v2_both_sides_derive_the_same_secret_and_authenticate_each_other() {
        let (caller, callee) = two_devices();
        let (pending, ephemeral) = accepted(&callee, &caller, "call-1");

        let agreement = caller_agree(&caller, &registered(&callee), "call-1", &ephemeral).unwrap();
        let (callee_shared, caller_authenticated) = callee_agree(
            &callee,
            &pending,
            "call-1",
            &agreement.identity_ciphertext,
            &agreement.ephemeral_ciphertext,
            Some(&registered(&caller)),
            Some(&agreement.proof),
        )
        .unwrap();

        assert_eq!(*agreement.shared, *callee_shared);
        assert!(caller_authenticated);

        let caller_setup = derive_call_setup(&agreement.shared, "caller", None).unwrap();
        let callee_setup = derive_call_setup(&callee_shared, "callee", None).unwrap();
        assert_eq!(caller_setup.send_key_b64, callee_setup.recv_key_b64);
        assert_eq!(caller_setup.recv_key_b64, callee_setup.send_key_b64);
        assert_eq!(caller_setup.safety_number, callee_setup.safety_number);
    }

    /// The point of the per-call key: everything a later thief of the callee's
    /// device could have — its long-term identity keys and a recording of the
    /// whole exchange — does not yield the call secret.
    #[test]
    fn v2_identity_key_and_transcript_alone_do_not_yield_the_call_secret() {
        let (caller, callee) = two_devices();
        let (pending, ephemeral) = accepted(&callee, &caller, "call-1");
        let agreement = caller_agree(&caller, &registered(&callee), "call-1", &ephemeral).unwrap();
        // The call happens; the per-call private key is then destroyed.
        drop(pending);

        // The thief has the identity (so the identity half decapsulates) but
        // must guess at the per-call half.
        let guess = PendingCallKey {
            keypair: LocalKemKeypair::generate(),
            caller_user_id: caller.user_id.clone(),
            caller_device_id: caller.device_id.clone(),
            created_at: 0,
        };
        let (wrong, _) = callee_agree(
            &callee,
            &guess,
            "call-1",
            &agreement.identity_ciphertext,
            &agreement.ephemeral_ciphertext,
            Some(&registered(&caller)),
            Some(&agreement.proof),
        )
        .unwrap();
        assert_ne!(*agreement.shared, *wrong);

        // And the per-call half alone is not the secret either: it is a
        // different value from the legacy, identity-only derivation too.
        let identity_only = decapsulate(
            &callee.kem.x25519_secret,
            &callee.kem.mlkem_secret,
            &agreement.identity_ciphertext,
            format!("{KEM_INFO_V2_IDENTITY}call-1").as_bytes(),
        )
        .unwrap();
        assert_ne!(*agreement.shared, identity_only);
    }

