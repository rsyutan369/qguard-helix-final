/* ═══════════════════════════════════════════════════════════ 6 · the defence */

function DefenceEvidencePanel() {
  const emit = useEmit();
  const [algorithm, setAlgorithm] = React.useState('ML-KEM-768');
  const [exchange, setExchange] = React.useState<KemExchange | null>(null);
  const [busy, setBusy] = React.useState(false);

  const run = React.useCallback(
    (id: string) => {
      setBusy(true);
      // Timer, not rAF: see the key-schedule panel above.
      setTimeout(() => {
        const result = runKemExchange(id);
        setExchange(result);
        setBusy(false);
        emit(
          result.agreed ? 'good' : 'alert',
          'ml-kem',
          `${id} keygen ${result.timings.keygenMs.toFixed(2)}ms · encap ${result.timings.encapsulateMs.toFixed(2)}ms · decap ${result.timings.decapsulateMs.toFixed(2)}ms · ek ${result.encapsulationKey.length}B ct ${result.ciphertext.length}B · secrets ${result.agreed ? 'agree' : 'DIVERGE'}`,
        );
      });
    },
    [emit],
  );

  React.useEffect(() => run(algorithm), [algorithm, run]);

  return (
    <div className="space-y-4">
      <p className="text-[12.5px] leading-relaxed" style={{ color: QSR.inkSoft }}>
        The replacement is a key encapsulation mechanism, not a new cipher. Below, your browser generates a real FIPS 203
        keypair, encapsulates a shared secret to it, decapsulates it from the other side, and checks that both halves landed on
        the same 32 bytes.
      </p>

      <div className="flex flex-wrap items-center gap-2">
        {['ML-KEM-512', 'ML-KEM-768', 'ML-KEM-1024'].map((id) => (
          <button
            key={id}
            type="button"
            onClick={() => setAlgorithm(id)}
            className="rounded-md border px-2.5 py-1.5 font-mono text-[10px] font-bold transition-colors"
            style={{
              borderColor: id === algorithm ? tint(QSR.quantum, 0.5) : QSR.hairline,
              background: id === algorithm ? tint(QSR.quantum, 0.14) : QSR.well,
              color: id === algorithm ? QSR.quantum : QSR.inkMuted,
            }}
          >
            {id}
          </button>
        ))}
        <ActionButton variant="ghost" accent={QSR.quantum} onClick={() => run(algorithm)} busy={busy}>
          Re-run exchange
        </ActionButton>
      </div>

      {exchange && (
        <>
          <div className="grid gap-3 sm:grid-cols-4">
            <StatTile label="Keygen" value={exchange.timings.keygenMs.toFixed(2)} unit="ms" provenance="measured" accent={QSR.quantum} />
            <StatTile label="Encapsulate" value={exchange.timings.encapsulateMs.toFixed(2)} unit="ms" provenance="measured" accent={QSR.quantum} />
            <StatTile label="Decapsulate" value={exchange.timings.decapsulateMs.toFixed(2)} unit="ms" provenance="measured" accent={QSR.quantum} />
            <StatTile
              label="Secrets agree"
              value={exchange.agreed ? 'YES' : 'NO'}
              provenance="measured"
              accent={exchange.agreed ? QSR.safe : QSR.broken}
              note="byte-for-byte"
            />
          </div>

          <div className="grid gap-3 lg:grid-cols-2">
            <div className="rounded-lg border p-3.5" style={{ borderColor: QSR.hairline, background: QSR.well }}>
              <div className="mb-2 flex items-center justify-between">
                <span className="font-mono text-[9px] font-bold uppercase tracking-[0.18em]" style={{ color: QSR.inkMuted }}>
                  Live output vs FIPS 203 Table 3
                </span>
                <Cite source="fips203" />
              </div>
              {exchange.sizeCheck.map((check) => (
                <DataRow
                  key={check.field}
                  label={check.field}
                  value={
                    <span className="flex items-center gap-1.5">
                      {check.observed} B
                      <span style={{ color: check.matches ? QSR.safe : QSR.broken }}>{check.matches ? '✓' : `≠ ${check.published}`}</span>
                    </span>
                  }
                  provenance="measured"
                  accent={check.matches ? QSR.ink : QSR.broken}
                />
              ))}
            </div>

            <div className="rounded-lg border p-3.5" style={{ borderColor: QSR.hairline, background: QSR.well }}>
              <div className="mb-2 font-mono text-[9px] font-bold uppercase tracking-[0.18em]" style={{ color: QSR.inkMuted }}>
                Material generated a moment ago
              </div>
              <div className="space-y-2.5">
                {[
                  { label: 'Encapsulation key', bytes: exchange.encapsulationKey, colour: QSR.quantum },
                  { label: 'Ciphertext', bytes: exchange.ciphertext, colour: QSR.live },
                  { label: 'Shared secret (initiator)', bytes: exchange.sharedSecretInitiator, colour: QSR.safe },
                  { label: 'Shared secret (responder)', bytes: exchange.sharedSecretResponder, colour: QSR.safe },
                ].map((row) => (
                  <div key={row.label}>
                    <div className="font-mono text-[9px] uppercase tracking-[0.14em]" style={{ color: QSR.inkFaint }}>
                      {row.label} · {row.bytes.length} B
                    </div>
                    <div className="break-all font-mono text-[10px]" style={{ color: row.colour }}>
                      {toHex(row.bytes, 24)}
                      {row.bytes.length > 24 && '…'}
                    </div>
                  </div>
                ))}
              </div>
            </div>
          </div>

          <div className="flex flex-wrap gap-1.5">
            <Chip label="Hardness" value={exchange.standard?.hardness ?? '—'} accent={QSR.quantum} />
            <Chip label="NIST category" value={exchange.standard?.category ?? '—'} accent={QSR.quantum} />
          </div>
        </>
      )}

      <Callout tone="good" title="Why this is tractable">
        <span className="flex items-start gap-2">
          <ShieldCheck className="mt-0.5 h-3.5 w-3.5 shrink-0" style={{ color: QSR.safe }} />
          <span>
            Nothing about the record layer changes. AES-256, SHA-384 and the whole transcript machinery stay exactly as they are;
            only the key agreement and the signatures move. That is why a migration measured in years rather than decades is
            realistic — and why published transition milestones should guide planning independently of CRQC estimates.
          </span>
        </span>
      </Callout>
    </div>
  );
}

