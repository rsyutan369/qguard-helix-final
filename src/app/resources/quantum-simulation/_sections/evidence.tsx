/* ═══════════════════════════════════════════════════════ 1 · the handshake */

function HandshakeEvidencePanel({ crypto }: { crypto: ScenarioCryptoProfile }) {
  const emit = useEmit();
  const [groupId, setGroupId] = React.useState(crypto.groupId);
  const [hovered, setHovered] = React.useState<number | null>(null);
  const [nonce, setNonce] = React.useState(0);

  React.useEffect(() => setGroupId(crypto.groupId), [crypto.groupId]);

  const evidence: HandshakeEvidence = React.useMemo(() => {
    const group = namedGroup(groupId);
    const keyShare = group && group.kind === 'hybrid' ? hybridKeyShare(group.name) : undefined;
    return buildClientHello({ serverName: 'payments.internal.example', groupId, keyShare });
    // `nonce` re-rolls the record so the reader can see the random fields change.
  }, [groupId, nonce]);

  const rows = React.useMemo(() => toHexRows(evidence.bytes, evidence.fields, 256), [evidence]);
  const group = evidence.group;

  React.useEffect(() => {
    emit(
      evidence.harvestable ? 'alert' : 'good',
      'tls',
      `ClientHello encoded — ${evidence.bytes.length} B, group ${group.name} (0x${group.id.toString(16).padStart(4, '0')}), key_share ${group.clientShareBytes} B · ${evidence.harvestable ? 'HARVESTABLE' : 'not harvestable'}`,
    );
  }, [emit, evidence, group]);
  const activeField: ByteField | undefined = hovered === null ? undefined : evidence.fields[hovered];

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex flex-wrap gap-1.5">
          {[0x001d, 0x0017, 0x11ec, 0x11ed].map((id) => {
            const candidate = namedGroup(id);
            if (!candidate) return null;
            const selected = id === groupId;
            const accent = candidate.quantumBroken ? QSR.broken : QSR.quantum;
            return (
              <button
                key={id}
                type="button"
                onClick={() => setGroupId(id)}
                title={candidate.note}
                className="rounded-md border px-2.5 py-1.5 font-mono text-[10px] font-bold transition-colors"
                style={{
                  borderColor: selected ? tint(accent, 0.5) : QSR.hairline,
                  background: selected ? tint(accent, 0.14) : QSR.well,
                  color: selected ? accent : QSR.inkMuted,
                }}
              >
                0x{id.toString(16).padStart(4, '0')} {candidate.name}
              </button>
            );
          })}
        </div>
        <ActionButton variant="ghost" onClick={() => setNonce((n) => n + 1)}>
          Re-roll record
        </ActionButton>
      </div>

      <div
        className="rounded-lg border px-3.5 py-3"
        style={{ borderColor: tint(evidence.harvestable ? QSR.broken : QSR.quantum, 0.28), background: tint(evidence.harvestable ? QSR.broken : QSR.quantum, 0.07) }}
      >
        <div className="flex items-start gap-2.5">
          {evidence.harvestable ? (
            <Unlock className="mt-0.5 h-4 w-4 shrink-0" style={{ color: QSR.broken }} />
          ) : (
            <Lock className="mt-0.5 h-4 w-4 shrink-0" style={{ color: QSR.quantum }} />
          )}
          <p className="text-[12.5px] leading-relaxed" style={{ color: QSR.inkSoft }}>
            {evidence.verdict}
          </p>
        </div>
      </div>

      <div className="grid gap-4 lg:grid-cols-[minmax(0,1fr)_290px]">
        <div className="min-w-0">
          <div className="mb-2 flex items-center justify-between">
            <span className="font-mono text-[9px] font-bold uppercase tracking-[0.18em]" style={{ color: QSR.inkMuted }}>
              TLS 1.3 ClientHello · {evidence.bytes.length} bytes {evidence.bytes.length > 256 && '(first 256 shown)'}
            </span>
            <span className="flex items-center gap-1.5">
              <ProvenanceBadge kind="published" compact />
              <Cite source="rfc8446" />
            </span>
          </div>
          <div
            className="qsr-scroll overflow-x-auto rounded-lg border p-3 font-mono text-[10.5px] leading-[1.65]"
            style={{ borderColor: QSR.hairline, background: QSR.wellSolid }}
          >
            {rows.map((row) => (
              <div key={row.offset} className="flex gap-3 whitespace-pre">
                <span style={{ color: QSR.inkFaint }}>{row.offset.toString(16).padStart(4, '0')}</span>
                <span>
                  {row.bytes.map((byte, i) => {
                    const index = row.fieldIndex[i];
                    const field = index >= 0 ? evidence.fields[index] : undefined;
                    const colour = field ? FIELD_COLOR[field.emphasis] : QSR.inkFaint;
                    const isActive = hovered !== null && index === hovered;
                    return (
                      <span
                        key={i}
                        onMouseEnter={() => setHovered(index >= 0 ? index : null)}
                        onMouseLeave={() => setHovered(null)}
                        className="cursor-default rounded-[2px] px-[1px] transition-colors"
                        style={{ color: colour, background: isActive ? tint(colour, 0.28) : undefined }}
                      >
                        {byte.toString(16).padStart(2, '0')}{' '}
                      </span>
                    );
                  })}
                </span>
                <span style={{ color: QSR.inkFaint }}>{row.ascii}</span>
              </div>
            ))}
          </div>

          <div className="mt-2 flex flex-wrap gap-2.5">
            {(Object.keys(FIELD_COLOR) as Array<keyof typeof FIELD_COLOR>).map((key) => (
              <span key={key} className="flex items-center gap-1 font-mono text-[9px] uppercase tracking-[0.1em]" style={{ color: QSR.inkFaint }}>
                <span className="h-2 w-2 rounded-[2px]" style={{ background: FIELD_COLOR[key] }} />
                {key.replace('-', ' ')}
              </span>
            ))}
          </div>
        </div>

        <div className="space-y-3">
          <div className="min-h-[112px] rounded-lg border p-3" style={{ borderColor: QSR.hairline, background: QSR.well }}>
            <div className="font-mono text-[9px] font-bold uppercase tracking-[0.18em]" style={{ color: QSR.inkMuted }}>
              {activeField ? 'Field' : 'Hover a byte'}
            </div>
            {activeField ? (
              <>
                <div className="mt-1.5 font-mono text-[11.5px] font-bold" style={{ color: FIELD_COLOR[activeField.emphasis] }}>
                  {activeField.label}
                </div>
                <div className="mt-0.5 font-mono text-[9.5px]" style={{ color: QSR.inkFaint }}>
                  offset 0x{activeField.offset.toString(16)} · {activeField.length} byte{activeField.length === 1 ? '' : 's'}
                </div>
                {activeField.note && (
                  <p className="mt-2 text-[11px] leading-snug" style={{ color: QSR.inkSoft }}>
                    {activeField.note}
                  </p>
                )}
              </>
            ) : (
              <p className="mt-2 text-[11px] leading-snug" style={{ color: QSR.inkFaint }}>
                Every byte in this record is annotated. Hover to see what it is and why it matters to quantum risk.
              </p>
            )}
          </div>

          <div className="rounded-lg border p-3" style={{ borderColor: QSR.hairline, background: QSR.well }}>
            <DataRow label="IANA code point" value={`0x${group.id.toString(16).padStart(4, '0')}`} provenance="published" />
            <DataRow label="Client key share" value={`${group.clientShareBytes} B`} provenance="published" />
            <DataRow label="Server key share" value={`${group.serverShareBytes} B`} provenance="published" />
            <DataRow
              label="Classical strength"
              value={`${group.classicalBits}-bit`}
              provenance="published"
            />
            <DataRow
              label="Survives a CRQC"
              value={group.quantumBroken ? 'No' : 'Yes'}
              accent={group.quantumBroken ? QSR.broken : QSR.quantum}
              provenance="published"
            />
            <div className="mt-2 text-[11px] leading-snug" style={{ color: QSR.inkFaint }}>
              {group.note} <Cite source="ianaGroups" />
            </div>
          </div>
        </div>
      </div>

      <Callout tone="info" title="What this specimen is">
        Encoded here from the RFC 8446 grammar rather than captured from a wire — this page never contacts a network. The record's
        length fields are verified against its own byte count by the offline check tool, and for the hybrid groups the ML-KEM key
        share is real FIPS 203 key material generated in your browser a moment ago. The classical key shares — x25519 and the ECDH
        halves of the hybrids — are random bytes of the correct length rather than valid curve points, since it is the field's
        presence, position and size that the dump exists to show.
      </Callout>
    </div>
  );
}

