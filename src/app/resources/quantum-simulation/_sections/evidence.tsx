/**
 * Quantum Simulation Range — the evidence surfaces.
 *
 * Each of the six attack stages names one evidence surface, and this file is
 * all six. They are not illustrations of the stage; they are the artefact the
 * stage produces:
 *
 *   1 record       a byte-accurate TLS 1.3 ClientHello you can read field by field
 *   2 archive      the storage arithmetic that makes harvesting cheap
 *   3 order-find   a pointer into the live Shor simulator, with its current state
 *   4 recover      the real HKDF-SHA-256 key schedule, run in this browser
 *   5 expose       what the decrypted archive contains, from the scenario record
 *   6 migrate      a real ML-KEM encapsulation and the re-issued handshake
 *
 * The hex dump deserves a note. It is generated, not captured — this page never
 * touches a network — but it is generated by the same encoder rules RFC 8446
 * specifies, its length fields are checked by `tools/quantum-sim-check.ts`, and
 * for the hybrid groups its ML-KEM key share is genuine lattice material from
 * FIPS 203 key generation. It is a specimen, and it is labelled as one.
 */

