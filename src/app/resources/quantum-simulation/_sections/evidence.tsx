const SURFACE_TITLE: Record<string, { title: string; eyebrow: string; accent: string }> = {
  handshake: { title: 'The bytes an adversary records', eyebrow: 'Evidence · captured handshake', accent: QSR.broken },
  archive: { title: 'What the archive costs to keep', eyebrow: 'Evidence · storage economics', accent: QSR.model },
  shor: { title: "Shor's order-finding, actually executed", eyebrow: 'Evidence · quantum register', accent: QSR.quantum },
  'key-schedule': { title: 'From shared secret to AEAD key', eyebrow: 'Evidence · key schedule', accent: QSR.broken },
  exposure: { title: 'What the decrypted archive contains', eyebrow: 'Evidence · exposure', accent: QSR.broken },
  defence: { title: 'FIPS 203 key encapsulation, live', eyebrow: 'Evidence · remedy', accent: QSR.safe },
};

export default function EvidenceSurface({ surface, scenario, crypto, onOpenLab, lastShorRun }: EvidenceProps) {
  const meta = SURFACE_TITLE[surface] ?? SURFACE_TITLE.handshake;

  return (
    <Panel eyebrow={meta.eyebrow} title={meta.title} accent={meta.accent}>
      <AnimatePresence mode="wait">
        <motion.div key={surface} initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0, y: -6 }} transition={{ duration: 0.24 }}>
          {surface === 'handshake' && <HandshakeEvidencePanel crypto={crypto} />}
          {surface === 'archive' && <ArchiveEvidencePanel crypto={crypto} />}
          {surface === 'shor' && <OrderFindingEvidencePanel onOpenLab={onOpenLab} lastRun={lastShorRun} />}
          {surface === 'key-schedule' && <KeyScheduleEvidencePanel />}
          {surface === 'exposure' && <ExposureEvidencePanel scenario={scenario} crypto={crypto} />}
          {surface === 'defence' && <DefenceEvidencePanel />}
        </motion.div>
      </AnimatePresence>
    </Panel>
  );
}
