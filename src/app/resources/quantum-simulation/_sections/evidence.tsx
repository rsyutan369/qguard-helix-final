/* ═══════════════════════════════════════════════════ 4 · the key schedule */

function KeyScheduleEvidencePanel() {
  const emit = useEmit();
  const [result, setResult] = React.useState<KeyScheduleResult | null>(null);
  const [busy, setBusy] = React.useState(false);

  const run = React.useCallback(() => {
    setBusy(true);
    // Yield to paint so the busy state shows first. A timer rather than a rAF,
    // which does not fire in a background tab.
    setTimeout(() => {
      const sharedSecret = new Uint8Array(32);
      (globalThis.crypto as Crypto | undefined)?.getRandomValues?.(sharedSecret);
      const hello = buildClientHello({ serverName: 'payments.internal.example', groupId: 0x001d });
      const schedule = tls13KeySchedule(sharedSecret, transcriptHash(hello.bytes));
      setResult(schedule);
      setBusy(false);
      emit(
        'alert',
        'hkdf',
        `key schedule replayed from shared secret — ${schedule.steps.length} HKDF-SHA-256 operations in ${schedule.elapsedMs.toFixed(2)}ms · client_write_key ${toHex(schedule.clientWriteKey, 8)}…`,
      );
    });
  }, [emit]);

  React.useEffect(() => run(), [run]);

  return (
    <div className="space-y-4">
      <p className="text-[12.5px] leading-relaxed" style={{ color: QSR.inkSoft }}>
        Recovering the shared secret is not the end of the attack — it is the beginning of an entirely deterministic one. The TLS
        1.3 key schedule is HKDF-SHA-256 with fixed labels over a transcript the recorder already holds. Below is that schedule,
        actually executed in this browser, from a freshly generated shared secret over the SHA-256 transcript of the specimen
        ClientHello above. RFC 8446 feeds a different transcript to each stage; this walk-through uses the one transcript
        throughout, so the chain is the real one but the bytes are not any particular session&apos;s traffic keys.
      </p>

      <div className="flex flex-wrap items-center gap-3">
        <ActionButton onClick={run} busy={busy} accent={QSR.broken}>
          <KeyRound className="h-3.5 w-3.5" /> Derive from a fresh shared secret
        </ActionButton>
        {result && (
          <span className="font-mono text-[10px]" style={{ color: QSR.inkFaint }}>
            {result.steps.length} HKDF operations in {result.elapsedMs.toFixed(2)} ms
          </span>
        )}
      </div>

      {result && (
        <div className="space-y-1.5">
          {result.steps.map((step, index) => (
            <div key={step.ordinal}>
              <div
                className="rounded-lg border px-3.5 py-2.5"
                style={{
                  borderColor: step.consumesSharedSecret ? tint(QSR.broken, 0.4) : QSR.hairline,
                  background: step.consumesSharedSecret ? tint(QSR.broken, 0.08) : QSR.well,
                }}
              >
                <div className="flex flex-wrap items-baseline justify-between gap-2">
                  <span className="font-mono text-[11.5px] font-bold" style={{ color: step.consumesSharedSecret ? QSR.broken : QSR.ink }}>
                    {step.ordinal}. {step.name}
                  </span>
                  <ProvenanceBadge kind="measured" compact />
                </div>
                <div className="mt-1 font-mono text-[10px] leading-snug" style={{ color: QSR.inkMuted }}>
                  {step.operation}
                </div>
                <div className="mt-1.5 break-all font-mono text-[10px]" style={{ color: step.consumesSharedSecret ? QSR.broken : QSR.live }}>
                  {toHex(step.value, 16)}…
                </div>
                <p className="mt-1.5 text-[11px] leading-snug" style={{ color: QSR.inkSoft }}>
                  {step.significance}
                </p>
              </div>
              {index < result.steps.length - 1 && (
                <div className="flex justify-center py-0.5">
                  <ArrowDown className="h-3 w-3" style={{ color: QSR.inkFaint }} />
                </div>
              )}
            </div>
          ))}
        </div>
      )}

      <Callout tone="danger" title="The cipher was never the problem">
        AES-256-GCM is quantum-safe and is not attacked at any point in this chain. The attacker derives its key rather than
        searching for it, so the strength of the record layer is irrelevant — a session is exactly as strong as the key agreement
        that seeded it. <Cite source="rfc8446" inline /> §7.1.
      </Callout>
    </div>
  );
}

