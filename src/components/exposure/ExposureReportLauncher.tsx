'use client';

/**
 * The Report Studio launcher — one button, one lazily-loaded drawer, mounted by
 * every surface that holds an exposure assessment (Local, Dev and the History
 * record view).
 *
 * It lives apart from the Studio itself so the builder, the integrity code and
 * the five heavy document renderers (pdf-lib, docx, exceljs, pptxgenjs) are only
 * fetched when an operator actually opens the drawer — the scanner's first paint
 * must not carry a report engine. And it lives apart from the three panels so
 * they cannot drift on who may generate a report or how the drawer is mounted.
 */

import React from 'react';
import {
  FileBarChart,
  FileCode2,
  FileJson,
  FileSpreadsheet,
  FileText,
  Loader2,
  Presentation,
  ScrollText,
  ShieldCheck,
  Wrench,
  type LucideIcon,
} from 'lucide-react';
import { cn } from '@/lib/utils';
import { ACCENT, Panel, SectionLabel } from '@/components/quantum-scan/ui';
import { SCAN_MODE_LABEL, type ExposureAssessment } from '@/lib/scanner/exposure/types';
/* The catalogue only — importing it from `ExposureReport` would statically pull
   the builder (and zod, jose and @noble/hashes behind it) into the main bundle
   from a component that is always mounted, undoing the lazy split below. */
import { EXPOSURE_REPORT_TEMPLATES, type ExposureReportTemplate } from '@/services/reporting/ExposureReportSpec';
import type { ExposureReportRecord } from '@/services/reporting/ExposureReport';

const ExposureReportStudio = React.lazy(() => import('./ExposureReportStudio'));

/**
 * Who the report is generated by, and the fact that reporting is enabled at all.
 *
 * Passing this object is what turns the feature on: the authenticated dashboard
 * supplies it, and the anonymous `/public-scan` page does not, so an enterprise
 * report is never emitted from a surface with no tenant behind it.
 */
export interface ExposureReportAuthor {
  /** Printed on the cover as the author. Usually the signed-in user's email. */
  generatedBy: string;
}

export interface ExposureReportButtonProps {
  assessment: ExposureAssessment;
  author: ExposureReportAuthor;
  /** Set when the assessment was rebuilt from a stored record. */
  record?: ExposureReportRecord | null;
  className?: string;
  /** Rendered as the primary action (filled) rather than a secondary one. */
  prominent?: boolean;
}

export function ExposureReportButton({ assessment, author, record, className, prominent = true }: ExposureReportButtonProps) {
  const [open, setOpen] = React.useState(false);

  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        title="Build a validated, sealed enterprise report from this assessment"
        className={cn(
          'inline-flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-[11.5px] font-bold transition-colors',
          prominent
            ? 'border border-cyan-400/35 bg-cyan-400/[0.1] text-cyan-200 hover:bg-cyan-400/[0.18]'
            : 'border border-white/[0.08] text-slate-300 hover:border-cyan-400/30 hover:text-cyan-300',
          className,
        )}
      >
        <FileBarChart className="h-3.5 w-3.5" aria-hidden />
        Report Studio
      </button>
      {open && (
        <React.Suspense
          fallback={
            <div className="fixed inset-0 z-[70] grid place-items-center bg-black/60 backdrop-blur-[2px]" role="status" aria-live="polite">
              <span className="inline-flex items-center gap-2 rounded-xl border border-white/[0.1] bg-[#080d1a] px-4 py-3 text-[12px] font-bold text-slate-300">
                <Loader2 className="h-4 w-4 animate-spin text-cyan-300" aria-hidden /> Loading the report engine…
              </span>
            </div>
          }
        >
          <ExposureReportStudio
            open
            onClose={() => setOpen(false)}
            assessment={assessment}
            generatedBy={author.generatedBy}
            record={record ?? null}
          />
        </React.Suspense>
      )}
    </>
  );
}

/* ──────────────────────────────────────────────────────────── the panel ──── */

const TEMPLATE_ICON: Record<ExposureReportTemplate, LucideIcon> = {
  executive: FileBarChart,
  technical: FileSpreadsheet,
  remediation: Wrench,
  compliance: ScrollText,
};

const FORMAT_CHIPS: Array<{ label: string; icon: LucideIcon }> = [
  { label: 'PDF', icon: FileText },
  { label: 'Word', icon: FileText },
  { label: 'Excel', icon: FileSpreadsheet },
  { label: 'PowerPoint', icon: Presentation },
  { label: 'HTML', icon: FileCode2 },
  { label: 'CSV', icon: FileSpreadsheet },
  { label: 'JSON', icon: FileJson },
];

const nf = (value: number) => value.toLocaleString('en-US');

/**
 * The reporting card that closes the results stack.
 *
 * Deliberately informative rather than a bare call to action: it names the four
 * audiences, what each document will be built from and the fact that every
 * figure is reconciled against these panels before export. It does NOT build a
 * report model — that happens when the drawer opens, so reading the results
 * never pays for the report engine.
 */
export function ExposureReportPanel({ assessment, author, record }: { assessment: ExposureAssessment; author: ExposureReportAuthor; record?: ExposureReportRecord | null }) {
  return (
    <Panel className="overflow-hidden">
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-white/[0.06] px-5 py-3">
        <SectionLabel accent={ACCENT.emerald}>Enterprise Reporting</SectionLabel>
        <span className="font-mono text-[10px] text-slate-500">
          {nf(assessment.findings.length)} findings · {nf(assessment.exposures.length)} exposures · {nf(assessment.cbom.length)} components
        </span>
      </div>

      <div className="px-5 py-4">
        <p className="text-[12.5px] leading-relaxed text-slate-400">
          Build a board-ready document from this {SCAN_MODE_LABEL[assessment.task.mode]} mode assessment. Every figure is read from the same derivations the
          panels above render, and each document carries a reconciliation table proving it — so a report can never disagree with the screen it was generated
          from.
        </p>

        <div className="mt-3.5 grid grid-cols-[minmax(0,1fr)] gap-2 sm:grid-cols-2">
          {EXPOSURE_REPORT_TEMPLATES.map((spec) => {
            const Icon = TEMPLATE_ICON[spec.key];
            return (
              <div key={spec.key} className="flex gap-2.5 rounded-xl border border-white/[0.07] bg-white/[0.02] px-3 py-2.5">
                <span className="grid h-8 w-8 shrink-0 place-items-center rounded-lg border border-emerald-400/25 bg-emerald-400/[0.07] text-emerald-300">
                  <Icon className="h-4 w-4" aria-hidden />
                </span>
                <span className="min-w-0">
                  <span className="block text-[12px] font-black text-white">{spec.name}</span>
                  <span className="block font-mono text-[9px] font-bold uppercase tracking-[0.14em] text-slate-500">{spec.audience}</span>
                </span>
              </div>
            );
          })}
        </div>

        <div className="mt-3.5 flex flex-wrap items-center gap-1.5">
          {FORMAT_CHIPS.map((chip) => (
            <span
              key={chip.label}
              className="inline-flex items-center gap-1 rounded-lg border border-white/[0.08] bg-white/[0.02] px-2 py-0.5 font-mono text-[10px] text-slate-400"
            >
              <chip.icon className="h-3 w-3" aria-hidden />
              {chip.label}
            </span>
          ))}
        </div>

        <div className="mt-4 flex flex-wrap items-center gap-3">
          <ExposureReportButton assessment={assessment} author={author} record={record} className="px-4 py-2.5 text-[13px]" />
          <p className="flex min-w-0 items-start gap-1.5 text-[11px] leading-relaxed text-slate-500">
            <ShieldCheck className="mt-0.5 h-3.5 w-3.5 shrink-0 text-emerald-400" aria-hidden />
            <span>
              Validated before export and sealed with SHA3-256. Spreadsheet, CSV and JSON exports always carry every row; the narrative formats state anything
              they shorten.
            </span>
          </p>
        </div>
      </div>
    </Panel>
  );
}
